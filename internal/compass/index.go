package compass

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
	"unicode/utf8"
)

const (
	// IndexPath is INDEX.md's path relative to .compass/.
	IndexPath = "INDEX.md"
	// IndexMaxTokens caps the generated INDEX.md. Tokens are estimated as bytes/4, which is close
	// for English prose and errs high for markdown punctuation.
	IndexMaxTokens = 2000
	// ClaimMaxChars caps a claim: it is one line in INDEX.md and in the resume brief.
	ClaimMaxChars = 200

	indexHeader = "<!-- Generated by `compass index` from the records' frontmatter. Do not edit; rerun it. -->\n"
)

// EstimateTokens is the bytes/4 heuristic every cap in compass uses.
func EstimateTokens(text string) int { return (len(text) + 3) / 4 }

// GenerateIndex renders INDEX.md from the records. The output depends only on the files, never on
// the clock, so `compass check` can compare it byte for byte.
func GenerateIndex(repo *Repo, docs []*Doc) (string, error) {
	var global []*Doc
	byCategory := map[string][]*Doc{}
	var superseded []*Doc
	for _, doc := range docs {
		switch {
		case !doc.Live():
			superseded = append(superseded, doc)
		case doc.Global():
			global = append(global, doc)
		default:
			byCategory[doc.Category] = append(byCategory[doc.Category], doc)
		}
	}
	sortNewestFirst(global)
	for _, list := range byCategory {
		sortNewestFirst(list)
	}

	var head strings.Builder
	head.WriteString(indexHeader)
	fmt.Fprintf(&head, "# compass index — %s\n\n", repo.Name())
	head.WriteString("Start with `compass resume`: current-state, live global claims, uncommitted work.\n")
	head.WriteString("Records below are live; search all of .compass/ with `rg -i <term> .compass/`.\n")

	tail, err := indexTail(repo, superseded)
	if err != nil {
		return "", err
	}
	budget := IndexMaxTokens*4 - head.Len() - len(tail)

	var body strings.Builder
	sections := []struct {
		title string
		docs  []*Doc
		dir   string
	}{{"global (delivered by `compass resume`)", global, ""}}
	for _, category := range RecordCategories {
		sections = append(sections, struct {
			title string
			docs  []*Doc
			dir   string
		}{category, byCategory[category], category})
	}
	for _, section := range sections {
		if len(section.docs) == 0 {
			continue
		}
		block := "\n## " + section.title + "\n"
		shown := 0
		for _, doc := range section.docs {
			line := indexLine(doc)
			// Leave room for this section's overflow line and the rest of the headers.
			if body.Len()+len(block)+len(line)+120 > budget {
				break
			}
			block += line
			shown++
		}
		if hidden := len(section.docs) - shown; hidden > 0 {
			where := ".compass/" + section.dir
			if section.dir == "" {
				where = "`rg -l '^scope: global' .compass/`"
			} else {
				where = "`ls " + where + "/`"
			}
			block += fmt.Sprintf("- … %d more, not listed to stay under the index cap: %s\n", hidden, where)
		}
		if body.Len()+len(block) > budget && shown == 0 {
			continue
		}
		body.WriteString(block)
	}
	return head.String() + body.String() + tail, nil
}

// indexTail lists superseded records by ID only and counts files in folders that are not v3
// record categories, so an agent knows they exist without paying for them.
func indexTail(repo *Repo, superseded []*Doc) (string, error) {
	var tail strings.Builder
	if len(superseded) > 0 {
		sort.Slice(superseded, func(i, j int) bool { return superseded[i].Path < superseded[j].Path })
		var pairs []string
		for _, doc := range superseded {
			pairs = append(pairs, doc.ID+" → "+strings.Join(doc.SupersededBy, ", "))
		}
		line := strings.Join(pairs, "; ")
		if len(line) > 1200 {
			line = truncate(line, 1200)
		}
		fmt.Fprintf(&tail, "\n## superseded (%d, not delivered)\n%s\n", len(superseded), line)
	}
	entries, err := os.ReadDir(repo.Dir)
	if err != nil {
		return "", err
	}
	var others []string
	known := map[string]bool{"scratch": true}
	for _, category := range RecordCategories {
		known[category] = true
	}
	for _, entry := range entries {
		if !entry.IsDir() || known[entry.Name()] || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		count := 0
		_ = filepath.WalkDir(filepath.Join(repo.Dir, entry.Name()), func(path string, d os.DirEntry, err error) error {
			if err == nil && !d.IsDir() && strings.HasSuffix(path, ".md") {
				count++
			}
			return nil
		})
		others = append(others, fmt.Sprintf("`%s/` (%d)", entry.Name(), count))
	}
	if len(others) > 0 {
		fmt.Fprintf(&tail, "\n## other folders (not records, not indexed)\n%s\n", strings.Join(others, ", "))
	}
	return tail.String(), nil
}

func indexLine(doc *Doc) string {
	claim := doc.Claim
	if claim == "" {
		claim = "(no claim)"
	}
	return fmt.Sprintf("- [%s](%s) — %s\n", doc.ID, doc.Path, truncate(oneLine(claim), ClaimMaxChars))
}

// sortNewestFirst orders by date, then ID, both descending; decision numbers sort the same way.
func sortNewestFirst(docs []*Doc) {
	sort.SliceStable(docs, func(i, j int) bool {
		if docs[i].Date != docs[j].Date {
			return docs[i].Date > docs[j].Date
		}
		return docs[i].ID > docs[j].ID
	})
}

func oneLine(text string) string { return strings.Join(strings.Fields(text), " ") }

func truncate(text string, max int) string {
	if utf8.RuneCountInString(text) <= max {
		return text
	}
	runes := []rune(text)
	return string(runes[:max-1]) + "…"
}

// WriteIndex regenerates INDEX.md and reports whether its content changed.
func WriteIndex(repo *Repo) (bool, error) {
	docs, err := LoadDocs(repo.Dir)
	if err != nil {
		return false, err
	}
	text, err := GenerateIndex(repo, docs)
	if err != nil {
		return false, err
	}
	path := filepath.Join(repo.Dir, IndexPath)
	if old, err := os.ReadFile(path); err == nil && string(old) == text {
		return false, nil
	}
	return true, writeFileAtomic(path, []byte(text))
}

// writeFileAtomic writes through a temporary file in the same directory and renames it, so a
// crash never leaves a half-written file.
func writeFileAtomic(path string, data []byte) error {
	temp, err := os.CreateTemp(filepath.Dir(path), "."+filepath.Base(path)+".*")
	if err != nil {
		return err
	}
	defer os.Remove(temp.Name())
	if _, err := temp.Write(data); err != nil {
		temp.Close()
		return err
	}
	if err := temp.Close(); err != nil {
		return err
	}
	mode := os.FileMode(0o644)
	if info, err := os.Stat(path); err == nil {
		mode = info.Mode().Perm()
	}
	if err := os.Chmod(temp.Name(), mode); err != nil {
		return err
	}
	return os.Rename(temp.Name(), path)
}
